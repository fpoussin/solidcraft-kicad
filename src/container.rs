//! Recompress native payloads without changing SolidCraft's document or blob format.
use std::io::{Cursor, copy};

use zip::{CompressionMethod, ZipArchive, ZipWriter, write::SimpleFileOptions};

use crate::error::{Error, Result};

/// Native output storage policy; both modes are readable by stock SolidCraft.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, clap::ValueEnum)]
pub enum Compression {
    /// Lossless Deflate level six for mesh and STEP payloads.
    #[default]
    Compact,
    /// Store geometry uncompressed, favouring writing speed.
    Fast,
}

/// Only accepts containers generated by the native writer, never arbitrary inputs.
pub(crate) fn compact(bytes: &[u8]) -> Result<Vec<u8>> {
    fn zip_error(error: zip::result::ZipError) -> Error {
        Error::message(format!("compressing SolidCraft file: {error}"))
    }

    let mut source = ZipArchive::new(Cursor::new(bytes)).map_err(zip_error)?;
    let mut output = ZipWriter::new(Cursor::new(Vec::new()));
    let options = SimpleFileOptions::default()
        .compression_method(CompressionMethod::Deflated)
        .compression_level(Some(6));
    for index in 0..source.len() {
        let mut entry = source.by_index(index).map_err(zip_error)?;
        let name = entry.name().map_err(zip_error)?.into_owned();
        if name.starts_with("blobs/") && (name.ends_with(".mesh") || name.ends_with(".step")) {
            output.start_file(name, options).map_err(zip_error)?;
            copy(&mut entry, &mut output)?;
        } else {
            output.raw_copy_file(entry).map_err(zip_error)?;
        }
    }
    Ok(output.finish().map_err(zip_error)?.into_inner())
}

#[cfg(test)]
mod tests {
    use std::io::Read;

    use solidcraft_engine::{
        doc::{Document, FeatureKind, MeshData},
        io,
    };

    use super::*;

    #[test]
    fn compact_preserves_native_payloads_metadata_and_binary_precision()
    -> std::result::Result<(), Box<dyn std::error::Error>> {
        let mut doc = Document::new("compression fixture");
        doc.add_feature(
            FeatureKind::Import {
                file: "embedded.step".into(),
                step: "ISO-10303-21;\n/* embedded STEP payload */\n"
                    .repeat(128)
                    .into(),
                components: Vec::new(),
                skip: Vec::new(),
            },
            Some("substrate"),
        )?;
        let mesh = MeshData {
            name: "first".into(),
            positions: vec![-0., 0., 0., 1.0000000000000002, 0., 0., 0., 1., 0.],
            triangles: [0, 1, 2].repeat(128),
            color: Some([0.2, 0.4, 0.6]),
        };
        let mut second = mesh.clone();
        second.name = "second".into();
        doc.add_feature(
            FeatureKind::MeshImport {
                file: "embedded.glb".into(),
                meshes: vec![mesh, second],
            },
            Some("models"),
        )?;
        let fast = io::write_design_container(&doc)?;
        let compact = compact(&fast)?;
        assert!(compact.len() < fast.len() / 2);
        assert_eq!(
            super::compact(&fast)?,
            compact,
            "compression must be deterministic"
        );
        let reopened = io::read_design(&compact)?;
        assert_eq!(reopened, io::read_design(&fast)?);
        let FeatureKind::MeshImport { meshes, .. } = &reopened.features[1].kind else {
            return Err("missing native meshes".into());
        };
        assert_eq!(meshes[0].positions[0].to_bits(), (-0.0f64).to_bits());
        assert_eq!(
            meshes[0].positions[3].to_bits(),
            1.0000000000000002f64.to_bits()
        );

        let mut original = ZipArchive::new(Cursor::new(&fast))?;
        let mut compressed = ZipArchive::new(Cursor::new(&compact))?;
        assert_eq!(original.len(), compressed.len());
        assert_eq!(
            original
                .file_names()
                .filter_map(std::result::Result::ok)
                .filter(|n| n.ends_with(".mesh"))
                .count(),
            1
        );
        for index in 0..original.len() {
            let mut source = original.by_index(index)?;
            let name = source.name()?.into_owned();
            let mut target = compressed.by_index(index)?;
            assert_eq!(target.name()?, name);
            let (mut before, mut after) = (Vec::new(), Vec::new());
            source.read_to_end(&mut before)?;
            target.read_to_end(&mut after)?;
            assert_eq!(before, after, "payload changed: {name}");
            if name.starts_with("blobs/") {
                assert_eq!(target.compression(), CompressionMethod::Deflated);
            }
        }
        for name in ["document.json", "container.json"] {
            let (mut before, mut after) = (Vec::new(), Vec::new());
            original
                .by_index_raw(original.index_for_name(name).ok_or("missing metadata")?)?
                .read_to_end(&mut before)?;
            compressed
                .by_index_raw(compressed.index_for_name(name).ok_or("missing metadata")?)?
                .read_to_end(&mut after)?;
            assert_eq!(before, after, "metadata was recompressed: {name}");
        }
        Ok(())
    }
}
